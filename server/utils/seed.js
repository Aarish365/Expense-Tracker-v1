const DEFAULT_CATEGORIES = [
  ...['Salary', 'Business', 'Freelancing', 'Other Income'].map((name) => [name, 'income']),
  ...[
    'Food', 'Shopping', 'Rent', 'Transport', 'Bills',
    'Healthcare', 'Education', 'Entertainment', 'Travel', 'Other Expenses',
  ].map((name) => [name, 'expense']),
];

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;

const seed = async () => {
  try {
    const remote = process.argv.includes('--remote');
    const scope = remote ? '--remote' : '--local';
    const root = path.resolve(__dirname, '..', '..');
    const schemaPath = path.join(root, 'server', 'db', 'schema.sql');
    const sqlPath = path.join(root, 'server', 'db', 'seed.generated.sql');

    const schema = fs.readFileSync(schemaPath, 'utf8');
    const hash = await bcrypt.hash(DEMO_PASSWORD, 10);
    const timestamp = new Date().toISOString();
    const today = new Date();

    const lines = [
      '-- Generated by server/utils/seed.js. Do not edit by hand.',
      schema.trim(),
      '',
      'BEGIN TRANSACTION;',
      `DELETE FROM transactions WHERE userId IN (SELECT _id FROM users WHERE LOWER(email) = LOWER(${quote(DEMO_EMAIL)})) OR userId = ${quote(DEMO_USER_ID)};`,
      `DELETE FROM categories WHERE userId IN (SELECT _id FROM users WHERE LOWER(email) = LOWER(${quote(DEMO_EMAIL)})) OR userId = ${quote(DEMO_USER_ID)};`,
      `DELETE FROM budgets WHERE userId IN (SELECT _id FROM users WHERE LOWER(email) = LOWER(${quote(DEMO_EMAIL)})) OR userId = ${quote(DEMO_USER_ID)};`,
      `DELETE FROM users WHERE LOWER(email) = LOWER(${quote(DEMO_EMAIL)}) OR _id = ${quote(DEMO_USER_ID)};`,
      `INSERT INTO users (_id, name, email, password, openingBalance, createdAt, updatedAt) VALUES (${quote(DEMO_USER_ID)}, 'Demo User', ${quote(DEMO_EMAIL)}, ${quote(hash)}, 25000, ${quote(timestamp)}, ${quote(timestamp)});`,
    ];

    DEFAULT_CATEGORIES.forEach(([name, type]) => {
      lines.push(`INSERT INTO categories (_id, userId, name, type, isDefault, createdAt, updatedAt) VALUES (${quote(crypto.randomUUID())}, ${quote(DEMO_USER_ID)}, ${quote(name)}, ${quote(type)}, 1, ${quote(timestamp)}, ${quote(timestamp)});`);
    });

    let transactionCount = 0;
    MONTH_TEMPLATES.forEach((rows, monthIndex) => {
      const monthDate = new Date(today.getFullYear(), today.getMonth() - (3 - monthIndex), 1);
      rows.forEach(([rawTitle, amount, type, category, paymentMethod, description], index) => {
        const day = Math.min(5 + index * 3, 28);
        const date = new Date(monthDate.getFullYear(), monthDate.getMonth(), day).toISOString();
        lines.push(`INSERT INTO transactions (_id, userId, title, amount, type, category, date, paymentMethod, description, createdAt, updatedAt) VALUES (${quote(crypto.randomUUID())}, ${quote(DEMO_USER_ID)}, ${quote(rawTitle.trim())}, ${amount}, ${quote(type)}, ${quote(category)}, ${quote(date)}, ${quote(paymentMethod)}, ${quote(description)}, ${quote(timestamp)}, ${quote(timestamp)});`);
        transactionCount += 1;
      });
    });

    MONTH_TEMPLATES.forEach((_, monthIndex) => {
      const monthDate = new Date(today.getFullYear(), today.getMonth() - (3 - monthIndex), 1);
      lines.push(`INSERT INTO budgets (_id, userId, month, year, amount, createdAt, updatedAt) VALUES (${quote(crypto.randomUUID())}, ${quote(DEMO_USER_ID)}, ${monthDate.getMonth() + 1}, ${monthDate.getFullYear()}, 45000, ${quote(timestamp)}, ${quote(timestamp)});`);
    });

    lines.push('COMMIT;', '');
    fs.writeFileSync(sqlPath, lines.join('\n'), 'utf8');

    const wranglerBin = path.join(root, 'node_modules', 'wrangler', 'bin', 'wrangler.js');
    const result = spawnSync(process.execPath, [
      wranglerBin, 'd1', 'execute', DB_NAME, scope, '--file', sqlPath,
    ], {
      cwd: root,
      stdio: 'inherit',
    });

    if (result.error || result.status !== 0) {
      throw new Error(
        result.error
          ? result.error.message
          : `wrangler d1 execute exited with code ${result.status}`
      );
    }

    console.log('\nDemo data ready!');
    console.log(`  Email:    ${DEMO_EMAIL}`);
    console.log(`  Password: ${DEMO_PASSWORD}`);
    console.log(`  ${transactionCount} transactions across 4 months`);
    console.log(`  Target:   D1 database "${DB_NAME}" (${remote ? 'remote' : 'local'})\n`);
  } catch (error) {
    console.error('Seed failed:', error.message);
    process.exitCode = 1;
  }
};

seed();
